-- V1__create_users_and_transactions.sql
-- Flyway migration #1: creates the initial database schema for FinTrack.
-- Flyway runs files in order (V1, V2, ...) exactly once and records which have run.
--
-- SQL here uses ANSI-standard types so it runs identically on PostgreSQL
-- (production) and H2 (tests): GENERATED AS IDENTITY for auto-ids and
-- TIMESTAMP WITH TIME ZONE for timestamps.

-- ========================= USERS =========================
-- One row per person who signs up.
CREATE TABLE users (
    id            BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL UNIQUE,   -- login name; no duplicates
    password_hash VARCHAR(255)             NOT NULL,          -- scrambled password, never raw
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===================== TRANSACTIONS ======================
-- One row per income/expense entry. Each belongs to exactly one user.
CREATE TABLE transactions (
    id           BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,            -- which user owns this row
    amount       NUMERIC(12,2)            NOT NULL CHECK (amount > 0),  -- money, positive
    type         VARCHAR(10)              NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    category     VARCHAR(100)             NOT NULL,            -- e.g. Food, Rent, Salary
    note         VARCHAR(255),                                 -- optional free text
    occurred_on  DATE                     NOT NULL,            -- the date the money moved
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- FOREIGN KEY: ties each transaction to a real user. Enforces ownership.
    -- ON DELETE CASCADE = deleting a user deletes their transactions too.
    CONSTRAINT fk_transactions_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- Index to make "find all transactions for user X" fast (our most common query).
CREATE INDEX idx_transactions_user_id ON transactions (user_id);
